def iso_to_unix(iso):
    return int(datetime.fromisoformat(iso.replace("Z", "+00:00")).timestamp())


def unix_to_iso(t):
    return datetime.fromtimestamp(t, tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")


def kernel_names():
    """Kernel file names chosen by 01_download.py (read from data/raw/downloads.json)."""
    recs = json.loads((RAW / "downloads.json").read_text())
    return [Path(r["file"]).name for r in recs if r["kind"] == "kernel"]


def _split_spice_string(s, width=70):
    """SPICE text kernels allow strings up to 80 chars; longer ones continue with '+'."""
    parts = [s[i:i + width] for i in range(0, len(s), width)]
    return ", ".join([f"'{p}+'" for p in parts[:-1]] + [f"'{parts[-1]}'"])


def write_meta_kernel():
    """Write data/raw/kernels/lspb.tm listing the downloaded kernels with an absolute path."""
    names = kernel_names()
    path = KERNELS.as_posix()
    body = [
        "KPL/MK",
        "",
        "LSPB meta-kernel (generated by pipeline/common.py; do not edit).",
        "",
        "\\begindata",
        "",
        f"PATH_VALUES  = ( {_split_spice_string(path)} )",
        "PATH_SYMBOLS = ( 'K' )",
        "KERNELS_TO_LOAD = (",
        *[f"   '$K/{n}'" for n in names],
        ")",
        "",
        "\\begintext",
        "",
    ]
    META_KERNEL.write_text("\n".join(body))
    return META_KERNEL, names


def load_kernels():
    import spiceypy as sp
    mk, names = write_meta_kernel()
    sp.kclear()
    sp.furnsh(str(mk))
    return names


def update_manifest(section):
    """Merge keys into web/public/data/manifest.json (other phases add their own sections)."""
    OUT.mkdir(parents=True, exist_ok=True)
    data = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else {}
    data.update(section)
    data["build_date_utc"] = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    MANIFEST.write_text(json.dumps(data, indent=2))


def load_ephemeris():
    """Return (manifest_ephemeris_section, array[count, 6] float64)."""
    man = json.loads(MANIFEST.read_text())["ephemeris"]
    arr = np.fromfile(OUT / man["file"], dtype="<f4").reshape(-1, 6).astype(np.float64)
    assert arr.shape[0] == man["count"], "ephemeris.bin size does not match manifest count"
    return man, arr


def body_at(man, arr, unix_s):
    """Linear interpolation between the two nearest samples -> (sun_km[3], earth_km[3])."""
    f = (unix_s - man["utc_start_unix_s"]) / man["step_s"]
    i = int(math.floor(f))
    if i < 0 or i >= man["count"] - 1:
        raise ValueError("time outside ephemeris range")
    w = f - i
    v = arr[i] * (1 - w) + arr[i + 1] * w
    return v[:3], v[3:]


def stereo_fwd(lat_deg, lon_deg, r=MOON_RADIUS_M):
    """PRD 5.3 south polar stereographic, true scale at the pole: (lat, lon) deg -> (x, y) m."""
    lat, lon = np.radians(lat_deg), np.radians(lon_deg)
    rho = 2 * r * np.tan(np.pi / 4 + lat / 2)
    return rho * np.sin(lon), rho * np.cos(lon)


def stereo_inv(x, y, r=MOON_RADIUS_M):
    """Inverse of stereo_fwd: (x, y) m -> (lat, lon) deg, lon in (-180, 180]."""
    rho = np.hypot(x, y)
    lat = np.degrees(2 * np.arctan(rho / (2 * r)) - np.pi / 2)
    lon = np.degrees(np.arctan2(x, y))
    return lat, lon


def stereo_rho(lat_deg, r=MOON_RADIUS_M):
    return 2 * r * np.tan(np.pi / 4 + np.radians(lat_deg) / 2)


def az_el(lat_deg, lon_deg, body_km, height_m=0.0):
    """PRD section 5.2: azimuth (deg, clockwise from north, [0,360)) and elevation (deg)."""
    lat, lon = math.radians(lat_deg), math.radians(lon_deg)
    up = np.array([math.cos(lat) * math.cos(lon), math.cos(lat) * math.sin(lon), math.sin(lat)])
    east = np.array([-math.sin(lon), math.cos(lon), 0.0])
    north = np.array([-math.sin(lat) * math.cos(lon), -math.sin(lat) * math.sin(lon), math.cos(lat)])
    site = up * (MOON_RADIUS_M + height_m) / 1000.0
    v = np.asarray(body_km, dtype=float) - site
    e, n, u = v @ east, v @ north, v @ up
    el = math.degrees(math.asin(u / np.linalg.norm(v)))
    az = math.degrees(math.atan2(e, n)) % 360.0
    return az, el
